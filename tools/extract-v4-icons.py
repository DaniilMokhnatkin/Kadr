"""Generate native outline data from the canonical v4 SVGs (requires svgpathtools).

Coordinates stay in the source's 24-unit viewBox. Curves are sampled at <=0.5-unit
intervals, then Direct2D strokes the resulting paths with round joins and caps.
"""
import math
import re
from pathlib import Path
from xml.etree import ElementTree as ET
from svgpathtools import parse_path, Line

root=Path(__file__).resolve().parents[1]
html=(root/'design/reference/kadr-concept-v4.html').read_text(encoding='utf-8')
symbols=re.findall(r'<symbol\b.*?</symbol>',html,re.S)
out=['// Generated by tools/extract-v4-icons.py from Claude concept 04; do not redraw these icons.',
     'pub(super) type Outline = (&\'static [(f32,f32)],bool,bool);',
     'pub(super) fn outlines(name: &str) -> &\'static [Outline] {', '    match name {']
def number(v):
    s=f'{v:.4f}'.rstrip('0').rstrip('.')
    return ('0.0' if s in ('','-0') else s if '.' in s else s+'.0')
def emit(points,closed,filled):
    values=','.join('('+number(p.real)+','+number(p.imag)+')' for p in points)
    return f'            (&[{values}],{str(closed).lower()},{str(filled).lower()}),'
for symbol in symbols:
    element=ET.fromstring(symbol)
    out.append('        "'+element.attrib['id'][2:]+'" => &[')
    for shape in element:
        tag=shape.tag
        filled=shape.attrib.get('class')=='solid'
        a={k:float(v) for k,v in shape.attrib.items() if k not in ('class','d')}
        if tag=='path':
            for sub in parse_path(shape.attrib['d']).continuous_subpaths():
                points=[]
                for segment in sub:
                    n=1 if isinstance(segment,Line) else max(1,math.ceil(segment.length()/0.5))
                    points.extend(segment.point(i/n) for i in range(n))
                points.append(sub[-1].point(1))
                out.append(emit(points,sub.isclosed(),filled))
        elif tag in ('circle','ellipse'):
            cx,cy=a.get('cx',0),a.get('cy',0)
            rx,ry=a.get('r',a.get('rx',0)),a.get('r',a.get('ry',0))
            n=max(24,math.ceil(2*math.pi*max(rx,ry)/0.5))
            points=[complex(cx+rx*math.cos(i*2*math.pi/n),cy+ry*math.sin(i*2*math.pi/n)) for i in range(n)]
            out.append(emit(points,True,filled))
        elif tag=='rect':
            x,y,w,h,rr=a.get('x',0),a.get('y',0),a['width'],a['height'],a.get('rx',0)
            if rr:
                points=[]
                for cx,cy,start in [(x+w-rr,y+rr,-90),(x+w-rr,y+h-rr,0),(x+rr,y+h-rr,90),(x+rr,y+rr,180)]:
                    n=max(6,math.ceil(math.pi*rr/0.5))
                    points.extend(complex(cx+rr*math.cos(math.radians(start+90*i/n)),cy+rr*math.sin(math.radians(start+90*i/n))) for i in range(n+1))
            else:points=[complex(x,y),complex(x+w,y),complex(x+w,y+h),complex(x,y+h)]
            out.append(emit(points,True,filled))
        else:raise ValueError(tag)
    out.append('        ],')
out.extend(['        _ => &[],','    }','}'])
target=root/'crates/kadr-render/src/scene/glyphs/v4_data.rs'
target.parent.mkdir(parents=True,exist_ok=True)
target.write_text('\n'.join(out)+'\n',encoding='utf-8')
print(f'{len(symbols)} original SVG symbols exported to native path data')
